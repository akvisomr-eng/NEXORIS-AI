CREATE SCHEMA IF NOT EXISTS nexoris;
CREATE TABLE IF NOT EXISTS nexoris.app_releases (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version TEXT NOT NULL, channel TEXT NOT NULL DEFAULT 'preview' CHECK (channel IN ('preview','stable')),
 platform TEXT NOT NULL DEFAULT 'windows-x64', release_notes TEXT NOT NULL DEFAULT '',
 download_url TEXT, sha256 CHAR(64), published_at TIMESTAMPTZ, minimum_supported_version TEXT,
 is_published BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS app_releases_published_idx ON nexoris.app_releases (channel, published_at DESC) WHERE is_published = TRUE;
CREATE TABLE IF NOT EXISTS nexoris.service_catalog (
 service_code TEXT PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
 requires_internet BOOLEAN NOT NULL DEFAULT FALSE, requires_external_instrument BOOLEAN NOT NULL DEFAULT FALSE,
 enabled BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
